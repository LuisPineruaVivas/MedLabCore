begin;

create function pg_temp.expect_error(p_sql text, p_pattern text) returns void language plpgsql as $$
declare v_failed boolean := false;
begin
  begin
    execute p_sql;
  exception when others then
    v_failed := true;
    if sqlerrm !~ p_pattern then
      raise exception 'Expected error matching "%" but got "%" for: %', p_pattern, sqlerrm, p_sql;
    end if;
  end;
  if not v_failed then
    raise exception 'Expected error matching "%" but statement succeeded: %', p_pattern, p_sql;
  end if;
end;
$$;

create function pg_temp.assert_true(p_value boolean, p_label text) returns void language plpgsql as $$
begin
  if p_value is distinct from true then raise exception 'Assertion failed: %', p_label; end if;
end;
$$;

create function pg_temp.act_as(p_user uuid) returns void language plpgsql as $$
begin
  perform set_config('request.jwt.claims', json_build_object('sub', p_user, 'role', 'authenticated')::text, true);
  set local role authenticated;
end;
$$;

create function pg_temp.act_as_anon() returns void language plpgsql as $$
begin
  perform set_config('request.jwt.claims', '{"role":"anon"}', true);
  set local role anon;
end;
$$;

create temp table ids (k text primary key, v uuid);
insert into ids values
  ('orgA', gen_random_uuid()), ('orgB', gen_random_uuid()),
  ('adminA', gen_random_uuid()), ('secA', gen_random_uuid()), ('adminB', gen_random_uuid()),
  ('patA1', gen_random_uuid()), ('patA2', gen_random_uuid()), ('patB1', gen_random_uuid()),
  ('signedA', gen_random_uuid()), ('pendingA', gen_random_uuid()), ('orderB', gen_random_uuid());
grant select on ids to authenticated, anon;
create function pg_temp.id(p_key text) returns uuid language sql as $$ select v from ids where k = p_key $$;

insert into public.organizations (id, name) values (pg_temp.id('orgA'), 'Run2 Ident A'), (pg_temp.id('orgB'), 'Run2 Ident B');
insert into auth.users (id, email) select v, k || '@run2-ident.local' from ids where k in ('adminA', 'secA', 'adminB');
insert into public.profiles (id, org_id, role, full_name, email) values
  (pg_temp.id('adminA'), pg_temp.id('orgA'), 'lab_admin', 'Admin A', 'adminA@run2-ident.local'),
  (pg_temp.id('secA'), pg_temp.id('orgA'), 'secretary', 'Sec A', 'secA@run2-ident.local'),
  (pg_temp.id('adminB'), pg_temp.id('orgB'), 'lab_admin', 'Admin B', 'adminB@run2-ident.local')
on conflict (id) do update set org_id = excluded.org_id, role = excluded.role;
insert into public.patients (id, org_id, id_number, first_name, last_name, date_of_birth, gender, created_by) values
  (pg_temp.id('patA1'), pg_temp.id('orgA'), 'RUN2-ID-A1', 'Pa', 'Uno', '1990-01-01', 'femenino', pg_temp.id('adminA')),
  (pg_temp.id('patA2'), pg_temp.id('orgA'), 'RUN2-ID-A2', 'Pa', 'Dos', '1990-01-01', 'femenino', pg_temp.id('adminA')),
  (pg_temp.id('patB1'), pg_temp.id('orgB'), 'RUN2-ID-B1', 'Pb', 'Uno', '1990-01-01', 'femenino', pg_temp.id('adminB'));
insert into public.orders (id, org_id, patient_id, created_by, status, access_pin, firma_url) values
  (pg_temp.id('signedA'), pg_temp.id('orgA'), pg_temp.id('patA1'), pg_temp.id('adminA'), 'completada', 'RUN2PINA01', 'https://x/firma.png'),
  (pg_temp.id('pendingA'), pg_temp.id('orgA'), pg_temp.id('patA1'), pg_temp.id('adminA'), 'pendiente', 'RUN2PINA02', null),
  (pg_temp.id('orderB'), pg_temp.id('orgB'), pg_temp.id('patB1'), pg_temp.id('adminB'), 'completada', 'RUN2PINB01', null);
-- access_pin is generated by an insert trigger; set known dummy PINs afterwards.
update public.orders set access_pin = case id when pg_temp.id('signedA') then 'RUN2PINA01' when pg_temp.id('pendingA') then 'RUN2PINA02' else 'RUN2PINB01' end
where id in (pg_temp.id('signedA'), pg_temp.id('pendingA'), pg_temp.id('orderB'));
update public.orders set created_at = now() - interval '2 days' where id = pg_temp.id('orderB');

-- Completed-order identity lock ----------------------------------------------
select pg_temp.act_as(pg_temp.id('secA'));
select pg_temp.expect_error(format('update public.orders set patient_id = %L where id = %L', pg_temp.id('patA2'), pg_temp.id('signedA')),
  'ORDER_COMPLETED_LOCKED');
select pg_temp.expect_error(format('update public.orders set created_by = %L where id = %L', pg_temp.id('secA'), pg_temp.id('signedA')),
  'ORDER_COMPLETED_LOCKED');
-- A pending order can still be corrected to another patient of the same lab.
update public.orders set patient_id = pg_temp.id('patA2') where id = pg_temp.id('pendingA');
reset role;
select pg_temp.assert_true((select patient_id from public.orders where id = pg_temp.id('pendingA')) = pg_temp.id('patA2'),
  'pending order reassigned within the lab');

-- Same-org patient binding ----------------------------------------------------
select pg_temp.act_as(pg_temp.id('secA'));
select pg_temp.expect_error(format('update public.orders set patient_id = %L where id = %L', pg_temp.id('patB1'), pg_temp.id('pendingA')),
  'INVALID_PATIENT');
reset role;
-- Every writer is bound, not only API callers.
select pg_temp.expect_error(format(
  'insert into public.orders (org_id, patient_id, created_by) values (%L, %L, %L)', pg_temp.id('orgA'), pg_temp.id('patB1'), pg_temp.id('adminA')),
  'INVALID_PATIENT');

-- Portal: a cross-org row written before the trigger existed cannot be used.
alter table public.orders disable trigger trg_order_patient_same_org;
update public.orders set patient_id = pg_temp.id('patB1') where id = pg_temp.id('signedA');
alter table public.orders enable trigger trg_order_patient_same_org;
select pg_temp.act_as_anon();
select pg_temp.assert_true(
  (select count(*) from public.portal_get_patient_orders(pg_temp.id('patB1'), 'RUN2PINA01')) = 0,
  'lab-A PIN on a lab-B patient returns nothing');
select pg_temp.assert_true(
  (select count(*) from public.portal_get_patient_orders(pg_temp.id('patB1'), 'RUN2PINB01')) = 1,
  'lab-B PIN still returns the lab-B order only');
select pg_temp.assert_true(
  not exists (select 1 from public.portal_get_patient_orders(pg_temp.id('patB1'), 'RUN2PINB01') where order_id = pg_temp.id('signedA')),
  'lab-B portal view does not include the re-pointed lab-A order');
reset role;

do $$ begin raise notice 'Audit run-2 order identity passed'; end $$;
rollback;
